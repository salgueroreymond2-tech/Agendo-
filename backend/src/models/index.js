import { sequelize } from '../config/database.js';
import { defineUser } from './user.js';
import { defineBusiness } from './business.js';
import { defineService } from './service.js';
import { defineBusinessHour } from './business-hour.js';
import { defineSubscription } from './subscription.js';
import { defineBooking } from './booking.js';
import { defineBookingSlot } from './booking-slot.js';
import { defineOnboardingEvent } from './onboarding-event.js';
import { defineAcquisitionSource } from './acquisition-source.js';
import { defineBusinessFiscalProfile } from './business-fiscal-profile.js';
import { defineAuthSession } from './auth-session.js';

export const User = defineUser(sequelize);
export const Business = defineBusiness(sequelize);
export const Service = defineService(sequelize);
export const BusinessHour = defineBusinessHour(sequelize);
export const Subscription = defineSubscription(sequelize);
export const Booking = defineBooking(sequelize);
export const BookingSlot = defineBookingSlot(sequelize);
export const OnboardingEvent = defineOnboardingEvent(sequelize);
export const AcquisitionSource = defineAcquisitionSource(sequelize);
export const BusinessFiscalProfile = defineBusinessFiscalProfile(sequelize);
export const AuthSession = defineAuthSession(sequelize);

User.hasMany(Business, { foreignKey: 'ownerId', as: 'businesses', onDelete: 'RESTRICT' });
Business.belongsTo(User, { foreignKey: 'ownerId', as: 'owner' });
User.hasMany(AuthSession, { foreignKey: 'userId', as: 'sessions', onDelete: 'CASCADE' });
AuthSession.belongsTo(User, { foreignKey: 'userId', as: 'user' });
Business.hasMany(Service, { foreignKey: 'businessId', as: 'services', onDelete: 'RESTRICT' });
Service.belongsTo(Business, { foreignKey: 'businessId', as: 'business' });
Business.hasMany(BusinessHour, { foreignKey: 'businessId', as: 'hours', onDelete: 'RESTRICT' });
BusinessHour.belongsTo(Business, { foreignKey: 'businessId', as: 'business' });
Business.hasMany(Subscription, { foreignKey: 'businessId', as: 'subscriptions', onDelete: 'RESTRICT' });
Subscription.belongsTo(Business, { foreignKey: 'businessId', as: 'business' });
Business.hasMany(Booking, { foreignKey: 'businessId', as: 'bookings', onDelete: 'RESTRICT' });
Booking.belongsTo(Business, { foreignKey: 'businessId', as: 'business' });
Service.hasMany(Booking, { foreignKey: 'serviceId', as: 'bookings', onDelete: 'RESTRICT' });
Booking.belongsTo(Service, { foreignKey: 'serviceId', as: 'service' });
Booking.hasMany(BookingSlot, { foreignKey: 'bookingId', as: 'slots', onDelete: 'CASCADE' });
BookingSlot.belongsTo(Booking, { foreignKey: 'bookingId', as: 'booking' });
Business.hasMany(BookingSlot, { foreignKey: 'businessId', as: 'bookingSlots', onDelete: 'RESTRICT' });
BookingSlot.belongsTo(Business, { foreignKey: 'businessId', as: 'business' });
Business.hasMany(OnboardingEvent, { foreignKey: 'businessId', as: 'onboardingEvents', onDelete: 'RESTRICT' });
OnboardingEvent.belongsTo(Business, { foreignKey: 'businessId', as: 'business' });
User.hasMany(OnboardingEvent, { foreignKey: 'userId', as: 'onboardingEvents', onDelete: 'SET NULL' });
OnboardingEvent.belongsTo(User, { foreignKey: 'userId', as: 'user' });
Business.hasMany(AcquisitionSource, { foreignKey: 'businessId', as: 'acquisitionSources', onDelete: 'RESTRICT' });
AcquisitionSource.belongsTo(Business, { foreignKey: 'businessId', as: 'business' });
Business.hasMany(AcquisitionSource, { foreignKey: 'referralBusinessId', as: 'referrals', onDelete: 'SET NULL' });
AcquisitionSource.belongsTo(Business, { foreignKey: 'referralBusinessId', as: 'referralBusiness' });
Business.hasOne(BusinessFiscalProfile, { foreignKey: 'businessId', as: 'fiscalProfile', onDelete: 'RESTRICT' });
BusinessFiscalProfile.belongsTo(Business, { foreignKey: 'businessId', as: 'business' });
